import { sanitizeTerminalText } from '../../rendering/terminal-text.js';
import type { TuiRuntimeEvent } from '../../../types/runtime-events.js';

/** One validated next-message suggestion, bound to the Turn that produced it. */
export interface TuiPromptSuggestion {
  readonly sessionId: string;
  readonly turnId: string;
  readonly text: string;
  readonly promptVersion?: string;
  readonly elapsedMs?: number;
}

/** Fired once per suggestion and action, mirroring the Desktop `prompt_suggestion` metric. */
export type TuiPromptSuggestionMetric =
  | { readonly action: 'shown' | 'accepted'; readonly suggestion: TuiPromptSuggestion }
  | {
      readonly action: 'sent';
      readonly suggestion: TuiPromptSuggestion;
      readonly edited: boolean;
    };

/** Bound for every per-Session map; each entry is disposable. */
const MAX_REMEMBERED_SESSIONS = 32;
/** Matches the Desktop metric dedupe window. */
const MAX_REPORTED_SUGGESTIONS = 64;

/**
 * Holds the latest next-message suggestion per Session, as generated by the
 * Runtime after a settled Turn. The Runtime already cancels generation when a
 * new Turn starts; this store only keeps the TUI from showing a result that a
 * newer Turn, a rewind or a local send has superseded. Whether it is visible
 * (empty composer, idle Session, no side conversation…) is decided by the
 * composer projection.
 */
export class TuiPromptSuggestionStore {
  private readonly suggestions = new Map<string, TuiPromptSuggestion>();
  private readonly latestTurns = new Map<string, string>();
  /**
   * Sessions rewound or deleted since their last Turn start. The Runtime does
   * not cancel an in-flight suggestion on rewind, so its late result is refused
   * here until a newer Turn starts.
   */
  private readonly retiredSessions = new Map<string, true>();
  /** Each suggestion reports `shown` and `accepted` at most once, as on Desktop. */
  private readonly shownReports = new Set<string>();
  private readonly acceptedReports = new Set<string>();
  /**
   * Accepted suggestion per Session, kept until a send of it is admitted or a
   * newer Turn, rewind or deletion supersedes it, so a failed send can still be
   * counted when the restored draft is sent again.
   */
  private readonly accepted = new Map<string, TuiPromptSuggestion>();

  constructor(private readonly report: (metric: TuiPromptSuggestionMetric) => void = () => {}) {}

  /** Applies one Runtime event. Returns true when a stored suggestion changed. */
  observe(event: TuiRuntimeEvent): boolean {
    if (event.type === 'session.start' && event.sessionId) {
      if (event.turnId) remember(this.latestTurns, event.sessionId, event.turnId);
      this.retiredSessions.delete(event.sessionId);
      return this.clearSession(event.sessionId);
    }
    if (event.type === 'message.rewind' || event.type === 'session.deleted') {
      if (!event.sessionId) return false;
      remember(this.retiredSessions, event.sessionId, true);
      return this.clearSession(event.sessionId);
    }
    if (event.type !== 'turn.prompt_suggestion.generated') return false;
    // Generated from context the user has since rewound or deleted.
    if (this.retiredSessions.has(event.sessionId)) return false;
    const latest = this.latestTurns.get(event.sessionId);
    // A newer Turn already started in this Session: this result is stale.
    if (latest !== undefined && latest !== event.turnId) return false;
    // Rendered and filled verbatim, so it is made terminal-safe exactly once here.
    const text = sanitizeTerminalText(event.suggestion).trim();
    if (!text) return false;
    remember(this.suggestions, event.sessionId, {
      sessionId: event.sessionId,
      turnId: event.turnId,
      text,
      ...(event.promptVersion !== undefined ? { promptVersion: event.promptVersion } : {}),
      ...(event.elapsedMs !== undefined ? { elapsedMs: event.elapsedMs } : {}),
    });
    return true;
  }

  /** Drops every stored suggestion, e.g. when the user turns the feature off. */
  clear(): boolean {
    this.accepted.clear();
    const changed = this.suggestions.size > 0;
    this.suggestions.clear();
    return changed;
  }

  /** The suggestion that may be offered while `sessionId` is the visible Session. */
  candidate(sessionId: string | undefined): TuiPromptSuggestion | undefined {
    return sessionId ? this.suggestions.get(sessionId) : undefined;
  }

  /** Records that the composer rendered the current suggestion; reported once. */
  markShown(suggestion: TuiPromptSuggestion): void {
    if (!reportOnce(this.shownReports, suggestionKey(suggestion))) return;
    this.emit({ action: 'shown', suggestion });
  }

  /**
   * The user filled the composer with the suggestion. It stays stored, so
   * clearing the composer offers it again; only a send retires it.
   */
  accept(suggestion: TuiPromptSuggestion): void {
    remember(this.accepted, suggestion.sessionId, suggestion);
    if (!reportOnce(this.acceptedReports, suggestionKey(suggestion))) return;
    this.emit({ action: 'accepted', suggestion });
  }

  /**
   * A message was submitted to the Agent, which supersedes the Session's
   * suggestion. When the message came from an accepted suggestion, returns the
   * `sent` report to run once the Runtime admits the send, so a failed send is
   * never counted and the acceptance stays for the next send of that Session.
   */
  submitted(sessionId: string | undefined, text: string): (() => void) | undefined {
    if (!sessionId) return undefined;
    this.suggestions.delete(sessionId);
    const accepted = this.accepted.get(sessionId);
    if (!accepted || !text.trim()) return undefined;
    let reported = false;
    return () => {
      if (reported) return;
      reported = true;
      if (this.accepted.get(sessionId) === accepted) this.accepted.delete(sessionId);
      this.emit({ action: 'sent', suggestion: accepted, edited: text !== accepted.text });
    };
  }

  private clearSession(sessionId: string): boolean {
    // A superseded suggestion can no longer be sent as accepted.
    this.accepted.delete(sessionId);
    return this.suggestions.delete(sessionId);
  }

  private emit(metric: TuiPromptSuggestionMetric): void {
    try {
      this.report(metric);
    } catch {
      // Telemetry must never affect the composer or a send.
    }
  }
}

/** Insertion-ordered bounded map: the most recently touched Session is kept. */
function remember<T>(map: Map<string, T>, key: string, value: T): void {
  map.delete(key);
  map.set(key, value);
  while (map.size > MAX_REMEMBERED_SESSIONS) {
    const oldest = map.keys().next();
    if (oldest.done) return;
    map.delete(oldest.value);
  }
}

/** Bounded dedupe: true only the first time `key` is seen. */
function reportOnce(seen: Set<string>, key: string): boolean {
  if (seen.has(key)) return false;
  seen.add(key);
  while (seen.size > MAX_REPORTED_SUGGESTIONS) {
    const oldest = seen.values().next();
    if (oldest.done) break;
    seen.delete(oldest.value);
  }
  return true;
}

function suggestionKey(suggestion: TuiPromptSuggestion): string {
  return `${suggestion.sessionId}\u0000${suggestion.turnId}`;
}
