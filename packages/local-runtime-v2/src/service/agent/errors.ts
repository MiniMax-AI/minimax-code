export class AgentServiceError extends Error {
  readonly status: number;

  constructor(
    readonly code: AgentServiceErrorCode,
    message: string,
    status = statusFor(code),
    readonly details?: Readonly<Record<string, unknown>>,
  ) {
    super(message);
    this.name = 'AgentServiceError';
    this.status = status;
  }
}

